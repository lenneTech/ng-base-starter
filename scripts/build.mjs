#!/usr/bin/env node
/**
 * `pnpm run build`: the Angular production build plus the lt-monorepo entry contract.
 *
 * 1. `ng build --output-path <dir>`, where `<dir>` is `NG_OUTPUT_DIR` (default `.output`).
 *    The check chain sets `.output-check`, `lt dev test` sets `.output-test`, so neither
 *    overwrites the `.output` a local build or CI left behind.
 * 2. Writes `<dir>/server/index.mjs`, a shim that starts Angular's `server.mjs`. The
 *    lt-monorepo CI (`test -f projects/app/.output/server/index.mjs`, `node
 *    .output/server/index.mjs`), the Dockerfile and `lt dev test` all start the built app
 *    through that path, the one Nuxt's Nitro output has. Angular names its entry
 *    `server.mjs` and only listens when it is the main module, so the shim calls the
 *    exported `startServer()` instead of re-exporting.
 *
 * Exit code: the build's, or 1 when the build output lacks `server.mjs`.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, realpathSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/** The output dir for this build: `NG_OUTPUT_DIR`, default `.output`. */
export function resolveOutputDir(env = process.env) {
  const dir = (env.NG_OUTPUT_DIR || '').trim();
  return dir || '.output';
}

/** Content of `<dir>/server/index.mjs`. */
export const SHIM_SOURCE = [
  '// Generated by scripts/build.mjs: the entry lt-monorepo CI, the Dockerfile and `lt dev test` start.',
  "import { startServer } from './server.mjs';",
  '',
  'startServer();',
  '',
].join('\n');

/** Writes the shim into `<outputDir>/server/`; throws when Angular's `server.mjs` is missing there. */
export function writeServerShim(outputDir) {
  const serverDir = join(outputDir, 'server');
  if (!existsSync(join(serverDir, 'server.mjs'))) {
    throw new Error(`build: ${join(serverDir, 'server.mjs')} not found; the Angular SSR build produced no server entry.`);
  }
  const shim = join(serverDir, 'index.mjs');
  writeFileSync(shim, SHIM_SOURCE);
  return shim;
}

function main() {
  const outputDir = resolveOutputDir();
  const require = createRequire(import.meta.url);
  const ngBin = require.resolve('@angular/cli/bin/ng.js', { paths: [ROOT] });
  const result = spawnSync(process.execPath, [ngBin, 'build', `--output-path=${outputDir}`, ...process.argv.slice(2)], { cwd: ROOT, stdio: 'inherit' });
  if (result.status !== 0) {
    process.exit(result.status ?? 1);
  }
  try {
    const shim = writeServerShim(resolve(ROOT, outputDir));
    console.log(`build: wrote ${shim}`);
  } catch (error) {
    console.error(String(error instanceof Error ? error.message : error));
    process.exit(1);
  }
}

function isCliEntry() {
  try {
    return realpathSync(process.argv[1] ?? '') === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (isCliEntry()) {
  main();
}
